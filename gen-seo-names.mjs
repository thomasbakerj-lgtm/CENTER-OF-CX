/* gen-seo-names.mjs
 *
 * Writes the slug to [display name, category key] map into src/lib/seo.js,
 * between the VENDOR_NAMES markers. Run from the repo ROOT after adding or
 * renaming any vendor: node gen-seo-names.mjs
 *
 * WHY THE CATEGORY IS IN THE MAP
 *
 * Resolving the display name alone fixed one defect and created another. The
 * same vendor holds a profile in up to five categories under five suffixed
 * slugs, so name-only titles collapsed 96 routes onto 38 duplicate titles,
 * with Five9, Talkdesk and Amazon Connect each rendering five byte-identical
 * ones. The category is the discriminator. Only its key is stored; the human
 * label is resolved in seo.js from CATEGORIES, so it cannot drift.
 *
 * WHY A GENERATED MAP AND NOT AN IMPORT
 *
 * seo.js is imported by App.jsx, which is the root shell and can never be
 * lazy-loaded. If seo.js imported the eight vendor data files directly, every
 * byte of vendor data would be pinned into the entry chunk permanently, and
 * route-level code splitting (tracker 10-01 through 10-03) would become
 * impossible. The bundle is currently one chunk at roughly 2,900 kB raw with
 * majority mobile traffic, and that is the largest open reachability defect on
 * the platform. A correct title is not worth foreclosing the fix for it.
 *
 * The cost of a generated map is drift: a vendor added without regenerating
 * would silently fall back to the slug. seo.test.mjs closes that hole by
 * asserting the map matches the live data files exactly, so drift fails the
 * suite instead of shipping a wrong title.
 *
 * DISPLAY NAME FIELD
 *
 * Seven data files carry `name`. WEMData carries `vendor` instead, which is
 * what VendorProfile.jsx renders in its H1 for that branch. The resolver is
 * therefore `v.name || v.vendor`, and it must stay that way, because the title
 * has to match the heading a reader sees on the page.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { vendors } from "./VendorData.js";
import { ivaVendors } from "./IVAData.js";
import { agentAssistVendors } from "./AgentAssistData.js";
import { marketLayers } from "./WEMData.js";
import { analyticsVendors } from "./AnalyticsData.js";
import { acdVendors } from "./ACDRoutingData.js";
import { deVendors } from "./DigitalEngagementData.js";
import { paymentVendors } from "./PaymentData.js";

const ROOT = dirname(fileURLToPath(import.meta.url));
const SEO = join(ROOT, "src", "lib", "seo.js");

const START = "/* VENDOR_NAMES_START generated by gen-seo-names.mjs, do not hand edit */";
const END = "/* VENDOR_NAMES_END */";

/* Single source of truth for how each data file is walked and which field
   carries the display name. seo.test.mjs imports this to rebuild the expected
   map, so the harness and the generator can never disagree about shape. */
/* Which category page each data file backs. Names alone do not identify a
   route: 96 of 282 vendor routes render a vendor that also holds a profile in
   another category, and Five9, Talkdesk and Amazon Connect each hold five. The
   category is what makes the title unique. Keys match CATEGORIES in
   src/lib/verticals.js, which is where seo.js resolves the human label, so the
   label itself is never copied here and cannot drift out of agreement. */
export const FILE_CATEGORY = {
  "VendorData.js": "ccaas",
  "IVAData.js": "iva",
  "AgentAssistData.js": "agent-assist",
  "WEMData.js": "wem-qm",
  "AnalyticsData.js": "analytics",
  "ACDRoutingData.js": "acd-routing",
  "DigitalEngagementData.js": "digital-engagement",
  "PaymentData.js": "payments",
};

export function collectVendorNames() {
  const out = [];
  const push = (file, slug, name) =>
    out.push({ file, slug, name, cat: FILE_CATEGORY[file] });

  for (const [slug, v] of Object.entries(vendors)) push("VendorData.js", slug, v.name);
  for (const [slug, v] of Object.entries(ivaVendors)) push("IVAData.js", slug, v.name);
  for (const v of agentAssistVendors) push("AgentAssistData.js", v.slug, v.name);
  for (const layer of Object.values(marketLayers)) {
    for (const v of layer.vendors) push("WEMData.js", v.slug, v.name || v.vendor);
  }
  for (const v of analyticsVendors) push("AnalyticsData.js", v.slug, v.name);
  for (const v of acdVendors) push("ACDRoutingData.js", v.slug, v.name);
  for (const v of deVendors) push("DigitalEngagementData.js", v.slug, v.name);
  for (const v of paymentVendors) push("PaymentData.js", v.slug, v.name);

  return out;
}

/* A slug present in two files resolves to whichever accessor VendorProfile.jsx
   consults first, and the loser becomes an unreachable page with no error. That
   is exactly how the Sprinklr IVA profile went missing. Refuse to generate. */
export function findCollisions(rows) {
  const seen = new Map();
  const hits = [];
  for (const r of rows) {
    if (seen.has(r.slug)) hits.push({ slug: r.slug, files: [seen.get(r.slug), r.file] });
    else seen.set(r.slug, r.file);
  }
  return hits;
}

function main() {
  const rows = collectVendorNames();

  const collisions = findCollisions(rows);
  if (collisions.length) {
    console.error("gen-seo-names: slug collisions, refusing to generate:");
    for (const c of collisions) console.error(`  ${c.slug}  ${c.files.join(" + ")}`);
    process.exit(1);
  }

  const nameless = rows.filter((r) => !r.name);
  if (nameless.length) {
    console.error("gen-seo-names: entries with no display name, refusing to generate:");
    for (const r of nameless) console.error(`  ${r.file}  ${r.slug}`);
    process.exit(1);
  }

  /* A data file added without a FILE_CATEGORY entry would emit a null category
     and collapse its routes back onto duplicate titles. Refuse rather than
     ship the regression this map exists to prevent. */
  const uncategorised = rows.filter((r) => !r.cat);
  if (uncategorised.length) {
    console.error("gen-seo-names: entries with no category, refusing to generate:");
    for (const r of uncategorised) console.error(`  ${r.file}  ${r.slug}`);
    process.exit(1);
  }

  const sorted = [...rows].sort((a, b) => a.slug.localeCompare(b.slug));
  const body = sorted
    .map((r) => `  ${JSON.stringify(r.slug)}: [${JSON.stringify(r.name)}, ${JSON.stringify(r.cat)}],`)
    .join("\n");

  const block = [
    START,
    `/* ${sorted.length} vendor profiles. Regenerate with: node gen-seo-names.mjs */`,
    "const VENDOR_NAMES = {",
    body,
    "};",
    END,
  ].join("\n");

  const src = readFileSync(SEO, "utf8");
  const s = src.indexOf(START);
  const e = src.indexOf(END);
  if (s === -1 || e === -1 || e < s) {
    console.error(`gen-seo-names: markers missing from ${SEO}. Nothing written.`);
    process.exit(1);
  }

  const next = src.slice(0, s) + block + src.slice(e + END.length);
  if (next === src) {
    console.log(`gen-seo-names: no change, ${sorted.length} entries already current.`);
    return;
  }
  writeFileSync(SEO, next);
  console.log(`gen-seo-names: wrote ${sorted.length} entries into src/lib/seo.js`);
}

if (process.argv[1] && process.argv[1].endsWith("gen-seo-names.mjs")) main();
